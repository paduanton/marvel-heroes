import { expect, test } from '@playwright/test';

test('preserves all discovery pages through built Nginx assets and FPM responses', async ({ page, context }) => {
  const problems: string[] = [];
  page.on('pageerror', error => problems.push(error.message));
  await page.goto('/?page=2&source=portfolio');
  const catalog = page.getByRole('region', { name: 'Character results', exact: true });
  await expect(catalog.getByRole('heading', { name: 'Captain Marvel', exact: true })).toBeVisible();
  await expect(catalog.getByRole('article')).toHaveCount(20);
  await catalog.getByRole('button', { name: 'First page', exact: true }).click();
  await page.getByRole('searchbox', { name: 'Search characters' }).fill('sp');
  await expect(catalog.getByRole('article')).toHaveCount(1);
  await catalog.getByRole('link', { name: 'Spider-Man', exact: true }).click();
  const stories = page.getByRole('region', { name: 'Related stories', exact: true });
  await expect(stories.getByRole('article')).toHaveCount(10);
  await stories.getByRole('button', { name: 'Next', exact: true }).click();
  await expect(stories.getByRole('heading', { name: 'A new beginning', exact: true })).toBeVisible();
  expect(new URL(page.url()).searchParams.get('stories_page')).toBe('2');
  await page.reload();
  await expect(stories.getByRole('heading', { name: 'A new beginning', exact: true })).toBeVisible();
  await stories.getByRole('link', { name: 'View comics', exact: true }).click();
  const comics = page.getByRole('region', { name: 'Comic results', exact: true });
  await expect(comics.getByRole('article')).toHaveCount(20);
  await comics.getByRole('button', { name: 'Next', exact: true }).click();
  await expect(comics.getByRole('heading', { name: 'Amazing Spider-Man #21', exact: true })).toBeVisible();
  expect(new URL(page.url()).searchParams.get('comics_page')).toBe('2');
  await page.reload();
  await expect(comics.getByRole('heading', { name: 'Amazing Spider-Man #21', exact: true })).toBeVisible();
  await page.getByRole('link', { name: 'Back to character', exact: true }).click();
  await expect(stories.getByRole('heading', { name: 'A new beginning', exact: true })).toBeVisible();
  await page.getByRole('link', { name: 'Back to characters', exact: true }).click();
  await expect(catalog.getByRole('article')).toHaveCount(1);
  expect(new URL(page.url()).search).toBe('?source=portfolio&query=sp');
  const cached = await context.request.get('/api/v1/characters?query=sp');
  expect(cached.status()).toBe(200);
  expect((await cached.json()).meta.cache.state).toBe('fresh');
  expect(cached.headers()['set-cookie']).toBeUndefined();
  expect(problems).toEqual([]);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: test.info().outputPath('paginated-nginx-discovery.png'), fullPage: true });
});
