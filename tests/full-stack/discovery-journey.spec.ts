import { randomUUID } from 'node:crypto';
import { expect, test } from '@playwright/test';

test('discovers, searches and paginates all resources through Laravel and Redis', async ({ page, context }) => {
  await context.setExtraHTTPHeaders({ 'X-Marvel-Test-Scenario': randomUUID(), 'X-Marvel-Test-Catalog': 'journey' });
  await page.route('**/api/v1/**', route => route.continue());
  const problems: string[] = [];
  page.on('pageerror', error => problems.push(error.message));
  await page.goto('/?source=portfolio');
  const catalog = page.getByRole('region', { name: 'Character results', exact: true });
  await expect(catalog.getByRole('link', { name: 'Spider-Man', exact: true })).toBeVisible();
  await expect(catalog.getByRole('article')).toHaveCount(20);
  await catalog.getByRole('button', { name: 'Next', exact: true }).click();
  await expect(catalog.getByRole('heading', { name: 'Captain Marvel', exact: true })).toBeVisible();
  await page.getByRole('searchbox', { name: 'Search characters' }).fill('sp');
  await expect(catalog.getByRole('article')).toHaveCount(1);
  await expect(catalog.getByRole('link', { name: 'Spider-Man', exact: true })).toBeVisible();
  expect(new URL(page.url()).searchParams.get('source')).toBe('portfolio');
  expect(new URL(page.url()).searchParams.has('page')).toBe(false);
  await page.goBack();
  await expect(catalog.getByRole('heading', { name: 'Captain Marvel', exact: true })).toBeVisible();
  await page.goForward();
  await expect(catalog.getByRole('link', { name: 'Spider-Man', exact: true })).toBeVisible();
  await catalog.getByRole('link', { name: 'Spider-Man', exact: true }).click();
  const stories = page.getByRole('region', { name: 'Related stories', exact: true });
  await expect(stories.getByRole('heading', { name: 'Origin of a hero', exact: true })).toBeVisible();
  await expect(stories.getByRole('article')).toHaveCount(10);
  await stories.getByRole('button', { name: 'Next', exact: true }).click();
  await expect(stories.getByRole('heading', { name: 'A new beginning', exact: true })).toBeVisible();
  await stories.getByRole('button', { name: 'First page', exact: true }).click();
  await expect(stories.getByRole('heading', { name: 'Origin of a hero', exact: true })).toBeVisible();
  await stories.getByRole('link', { name: 'View comics', exact: true }).first().click();
  const comics = page.getByRole('region', { name: 'Comic results', exact: true });
  await expect(comics.getByRole('heading', { name: 'Amazing Spider-Man #1', exact: true })).toBeVisible();
  await expect(comics.getByRole('article')).toHaveCount(20);
  await comics.getByRole('button', { name: 'Next', exact: true }).click();
  await expect(comics.getByRole('heading', { name: 'Amazing Spider-Man #21', exact: true })).toBeVisible();
  await comics.getByRole('button', { name: 'First page', exact: true }).click();
  await expect(comics.getByRole('heading', { name: 'Amazing Spider-Man #1', exact: true })).toBeVisible();
  await page.reload();
  await expect(comics.getByRole('heading', { name: 'Amazing Spider-Man #1', exact: true })).toBeVisible();
  await page.getByRole('link', { name: 'Back to character', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Spider-Man', exact: true })).toBeVisible();
  await page.getByRole('link', { name: 'Back to characters', exact: true }).click();
  await expect(catalog.getByRole('article')).toHaveCount(1);
  const repeated = await context.request.get('/api/v1/characters?query=sp&page=1&per_page=20');
  expect(repeated.status()).toBe(200);
  expect(repeated.headers()['x-test-upstream-calls']).toBe('8');
  expect((await repeated.json()).meta.cache.state).toBe('fresh');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect(problems).toEqual([]);
  await page.screenshot({ path: test.info().outputPath('integrated-discovery.png'), fullPage: true });
});
